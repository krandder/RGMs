"""Nested temporal partition model with analytically integrated categorical rows.

This benchmark is independently specified; it is not the RGM parameterization.
Observations are atomic states. A hierarchy groups these states recursively.
Each internal node has Markov rows while its parent group persists, and an
entry row when the process enters that group. The initial state is conditioned
on. No multinomial coefficient belongs in the likelihood of ordered records.
"""
from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
import json
import math
from typing import Any

import numpy as np
from scipy.special import gammaln, logsumexp


Tree = int | tuple


def leaves(tree: Tree) -> tuple[int, ...]:
    if isinstance(tree, int):
        return (tree,)
    return tuple(sorted(x for child in tree for x in leaves(child)))


def canonical(tree: Tree) -> Tree:
    if isinstance(tree, (int, np.integer)):
        return int(tree)
    return tuple(sorted((canonical(c) for c in tree), key=lambda c: leaves(c)[0]))


def nodes(tree: Tree) -> tuple[tuple[tuple[int, ...], tuple], ...]:
    if isinstance(tree, int):
        return ()
    return ((leaves(tree), tree),) + tuple(n for c in tree for n in nodes(c))


def depth(tree: Tree) -> int:
    return 0 if isinstance(tree, int) else 1 + max(depth(c) for c in tree)


@dataclass(frozen=True)
class Structure:
    tree: Tree
    controlled: tuple[tuple[int, ...], ...] = ()

    def __post_init__(self):
        object.__setattr__(self, 'tree', canonical(self.tree))
        object.__setattr__(self, 'controlled', tuple(sorted(tuple(sorted(c)) for c in self.controlled)))
        valid = {ls for ls, _ in nodes(self.tree)}
        if not set(self.controlled).issubset(valid):
            raise ValueError('Controlled groups must be internal nodes')

    @property
    def id(self) -> str:
        return json.dumps(self.to_dict(), separators=(',', ':'))

    @property
    def depth(self) -> int:
        return depth(self.tree)

    def to_dict(self) -> dict[str, Any]:
        return {'tree': self.tree, 'controlled': self.controlled}

    @classmethod
    def from_dict(cls, value: dict) -> 'Structure':
        return cls(canonical(value['tree']), tuple(tuple(c) for c in value.get('controlled', ())))


@dataclass(frozen=True)
class Transition:
    x: int
    action: int
    y: int


def structure_count(n: int, d: int) -> int:
    """Analytical count; no structures generated by this function."""
    if d == 1:
        return 1
    return math.comb(n - 1, n // 2 - 1) * structure_count(n // 2, d - 1) ** 2


def base_complexity(n: int, d: int) -> tuple[int, int]:
    """Free categorical parameters and internal nodes (without control masks)."""
    if d == 1:
        return n * (n - 1), 1
    # Root has two binary Markov rows. Every nonroot internal node additionally
    # has one entry row; final internal nodes have n/2**(d-1) atomic children.
    p, count = 2, 1
    for level in range(1, d):
        k = n // (2 ** level) if level == d - 1 else 2
        p += (2 ** level) * (k + 1) * (k - 1)
        count += 2 ** level
    return p, count


@lru_cache(maxsize=10000)
def _layout(structure: Structure):
    result = []
    for group, children in nodes(structure.tree):
        child_sets = tuple(frozenset(leaves(c)) for c in children)
        lookup = {leaf: j for j, child in enumerate(child_sets) for leaf in child}
        result.append((group, child_sets, lookup, group in structure.controlled))
    return tuple(result)


@lru_cache(maxsize=4)
def _history_arrays(history):
    return np.asarray([(r.x,r.action,r.y) for r in history],dtype=np.int64).reshape(-1,3).T


class PosteriorProblem:
    def __init__(self, n_leaves: int = 4, max_depth: int | None = None,
                 alpha: float = .5, infer_controls: bool = False,
                 complexity_penalty: float = .02, node_penalty: float = .15,
                 control_prior: float = .25):
        if n_leaves < 2 or n_leaves & (n_leaves - 1):
            raise ValueError('n_leaves must be a power of two >= 2')
        self.n_leaves = int(n_leaves)
        self.max_depth = max_depth or int(math.log2(n_leaves))
        if not 1 <= self.max_depth <= int(math.log2(n_leaves)):
            raise ValueError('Invalid maximum depth')
        if alpha <= 0 or not 0 < control_prior < 1:
            raise ValueError('Invalid Dirichlet or control prior')
        self.alpha = float(alpha)
        self.infer_controls = infer_controls
        self.control_prior = float(control_prior)
        weights = [-complexity_penalty * base_complexity(n_leaves, d)[0]
                   -node_penalty * base_complexity(n_leaves, d)[1]
                   for d in range(1, self.max_depth + 1)]
        self.log_depth_prior = np.asarray(weights) - logsumexp(weights)

    def log_prior(self, structure: Structure) -> float:
        d = structure.depth
        if d < 1 or d > self.max_depth or leaves(structure.tree) != tuple(range(self.n_leaves)):
            return -np.inf
        if structure.controlled and not self.infer_controls:
            return -np.inf
        value = self.log_depth_prior[d - 1] - math.log(structure_count(self.n_leaves, d))
        if self.infer_controls:
            c = len(structure.controlled)
            total = len(nodes(structure.tree))
            value += c * math.log(self.control_prior) + (total-c)*math.log1p(-self.control_prior)
        return float(value)

    def counts(self, structure: Structure, history) -> dict:
        counts = {}
        x,a,y = _history_arrays(tuple(history))
        if np.any(x<0) or np.any(x>=self.n_leaves) or np.any(y<0) or np.any(y>=self.n_leaves) or np.any((a<0)|(a>1)):
            raise ValueError('Record outside state/action domain')
        for group, child_sets, lookup, controlled in _layout(structure):
            k = len(child_sets)
            lu = np.full(self.n_leaves,k,dtype=np.int64)
            for leaf,j in lookup.items():
                lu[leaf] = j
            targets = lu[y]
            keep = targets < k
            acts = a[keep] if controlled else np.zeros(keep.sum(),dtype=np.int64)
            ids = (acts*(k+1) + lu[x[keep]])*k + targets[keep]
            rows = np.bincount(ids,minlength=(2 if controlled else 1)*(k+1)*k).reshape(-1,k)
            for row,c in enumerate(rows):
                if c.sum():
                    counts[(group,row//(k+1),row%(k+1))] = c
        return counts

    def log_evidence(self, structure: Structure, history) -> float:
        value = 0.
        a = self.alpha
        for c in self.counts(structure, history).values():
            value += gammaln(len(c)*a) - gammaln(c.sum()+len(c)*a)
            value += np.sum(gammaln(c+a) - gammaln(a))
        return float(value)

    def log_weight(self, structure: Structure, history) -> float:
        return self.log_prior(structure) + self.log_evidence(structure, history)

    def predictive(self, structure: Structure, x: int, action: int, history) -> np.ndarray:
        return self.predictive_from_counts(structure, x, action, self.counts(structure, history))

    def predictive_from_counts(self, structure: Structure, x: int, action: int, counts: dict) -> np.ndarray:
        result = np.ones(self.n_leaves)
        for group, child_sets, lookup, controlled in _layout(structure):
            row = lookup.get(x, len(child_sets))
            key = (group, action if controlled else 0, row)
            c = counts.get(key, np.zeros(len(child_sets)))
            probs = (c + self.alpha) / (c.sum() + len(c)*self.alpha)
            for j, child in enumerate(child_sets):
                result[list(child)] *= probs[j]
        return result


class TemporalWorld:
    """Fixed parameter draw and independent recursive transition simulator."""
    def __init__(self, structure: Structure, seed: int = 0, iid: bool = False,
                 concentration: float = 80., persistence: float = .92):
        self.structure = structure
        self.n_leaves = len(leaves(structure.tree))
        self.iid = iid
        self.tables = {}
        rng = np.random.default_rng(seed)

        def build(tree, level=0):
            if isinstance(tree, int):
                return
            group, k = leaves(tree), len(tree)
            actions = 2 if group in structure.controlled else 1
            table = np.empty((actions, k+1, k))
            for a in range(actions):
                for old in range(k+1):
                    if iid:
                        table[a, old] = np.full(k, 1/k)
                    elif old == k:
                        table[a, old] = rng.dirichlet(np.ones(k)*2)
                    else:
                        stay = max(.35, persistence - .18*level)
                        target = (old + a) % k
                        base = np.full(k, (1-stay)/(k-1))
                        base[target] = stay
                        table[a, old] = rng.dirichlet(concentration*base)
            self.tables[group] = table
            for child in tree:
                build(child, level+1)
        build(structure.tree)

    def predictive(self, x: int, action: int = 0) -> np.ndarray:
        result = np.zeros(self.n_leaves)
        def visit(tree, mass):
            if isinstance(tree, int):
                result[tree] += mass
                return
            group, k = leaves(tree), len(tree)
            old = next((j for j, child in enumerate(tree) if x in leaves(child)), k)
            table = self.tables[group]
            row = table[action if table.shape[0] == 2 else 0, old]
            for child, p in zip(tree, row):
                visit(child, mass*p)
        visit(self.structure.tree, 1.)
        return result

    def step(self, x: int, action: int, rng: np.random.Generator) -> int:
        tree = self.structure.tree
        while not isinstance(tree, int):
            group, k = leaves(tree), len(tree)
            old = next((j for j, child in enumerate(tree) if x in leaves(child)), k)
            table = self.tables[group]
            row = table[action if table.shape[0] == 2 else 0, old]
            tree = tree[int(rng.choice(k, p=row))]
        return tree

    def sample(self, n: int, seed: int = 0, randomized_actions: bool = False,
               reset: bool = False, initial: int = 0) -> list[Transition]:
        rng = np.random.default_rng(seed)
        x, records = initial, []
        for _ in range(n):
            if reset:
                x = int(rng.integers(self.n_leaves))
            a = int(rng.integers(2)) if randomized_actions else 0
            y = self.step(x, a, rng)
            records.append(Transition(x, a, y))
            x = y
        return records


def random_structure(n_leaves: int, d: int, seed: int = 0, controls: bool = False) -> Structure:
    rng = np.random.default_rng(seed)
    def make(group, level):
        if level == 1:
            return tuple(group)
        others = np.asarray(group[1:])
        left = tuple(sorted([group[0]] + rng.choice(others, len(group)//2-1, replace=False).tolist()))
        right = tuple(x for x in group if x not in left)
        return (make(left, level-1), make(right, level-1))
    tree = make(tuple(range(n_leaves)), d)
    controlled = tuple(g for g, _ in nodes(tree) if rng.random() < .5) if controls else ()
    return Structure(tree, controlled)
